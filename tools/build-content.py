#!/usr/bin/env python3
"""Rebuild core/bryars-content.js from the .md files in content/.
Run after editing any content file:  python3 tools/build-content.py"""
import os, json
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'app', 'src', 'main', 'assets', 'web')
C = os.path.join(ROOT, 'content')
def read(p): return open(p, encoding='utf-8').read()
core_parts = [f'aladaz/mastercore.part{i}.md' for i in range(1, 6)]
core = '\n\n'.join(read(os.path.join(C, p)).strip() for p in core_parts)
files = {}
for folder in ('aladaz', 'library'):
    d = os.path.join(C, folder)
    for f in sorted(os.listdir(d)):
        if f.endswith(('.md', '.txt')):
            files[f'{folder}/{f}'] = read(os.path.join(d, f))
out = {'core': core, 'coreParts': core_parts, 'files': files}
js = '/* GENERATED by tools/build-content.py - edit the .md files, not this file. */\n'
js += 'globalThis.BRYARS_CONTENT = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n'
open(os.path.join(ROOT, 'core', 'bryars-content.js'), 'w', encoding='utf-8').write(js)
print('wrote core/bryars-content.js:', len(files), 'files,', len(core), 'chars of core')
